-- Account scoring (engagement-derived + pipeline-derived signal, capped at 100)
-- account_score (rewritten 2026-06-30, items 2 + 4 of the coworker
-- pressure-test gap list):
--   - hard/soft split: event_weights.source IN ('ga4','gmail','salesforce')
--     counts as a "hard" (independently-observed) signal; 'manual' counts as
--     "soft" (self-reported). hard_points/soft_points are exposed alongside
--     the blended `score` so the Channel Recommendation AI (and the Account
--     360 dashboard) can weight hard signals more heavily instead of
--     treating every event type as equally trustworthy.
--   - diminishing returns: occurrence_rank (row_number per account+event_type
--     ordered by occurred_at) caps repeated low-effort events from inflating
--     score without limit — 1st occurrence of a given event_type counts at
--     full weight, 2nd at 0.4x, 3rd+ at 0x. Without this, e.g. 50 page_visit
--     events from one account could outscore a single meeting_booked.
create or replace view account_score as
 WITH event_weights AS (
   SELECT ee.account, ee.source, ee.event_type, ee.occurred_at,
     CASE ee.event_type
       WHEN 'opportunity_created' THEN 50 WHEN 'meeting_booked' THEN 40
       WHEN 'reply_or_meeting' THEN 30
       WHEN 'reply' THEN 20 WHEN 'email_reply' THEN 20 WHEN 'form_fill' THEN 25
       WHEN 'call_connected' THEN 25
       WHEN 'registration' THEN 15
       WHEN 'content_download' THEN 15 WHEN 'stage_change' THEN 15 WHEN 'partner_response' THEN 15
       WHEN 'linkedin_accept' THEN 10 WHEN 'email_click' THEN 5
       WHEN 'email_open' THEN 5 WHEN 'page_visit' THEN 5 WHEN 'profile_visit' THEN 5
       ELSE 2 END AS base_weight,
     row_number() OVER (PARTITION BY ee.account, ee.event_type ORDER BY ee.occurred_at) AS occurrence_rank
   FROM engagement_events ee WHERE ee.account IS NOT NULL
 ), ev AS (
   SELECT event_weights.account,
     sum(event_weights.base_weight::numeric * CASE event_weights.occurrence_rank
       WHEN 1 THEN 1.0 WHEN 2 THEN 0.4 ELSE 0 END) AS event_points,
     sum(event_weights.base_weight::numeric * CASE event_weights.occurrence_rank
       WHEN 1 THEN 1.0 WHEN 2 THEN 0.4 ELSE 0 END)
       FILTER (WHERE event_weights.source = ANY (ARRAY['ga4','gmail','salesforce'])) AS hard_event_points,
     sum(event_weights.base_weight::numeric * CASE event_weights.occurrence_rank
       WHEN 1 THEN 1.0 WHEN 2 THEN 0.4 ELSE 0 END)
       FILTER (WHERE event_weights.source = 'manual') AS soft_points,
     count(*) AS events, max(event_weights.occurred_at) AS last_event
   FROM event_weights
   GROUP BY event_weights.account
 ), base AS (
   SELECT pipeline_runs.company AS account,
     (max(CASE upper(COALESCE(pipeline_runs.coverage_label, ''))
            WHEN 'BROAD' THEN 15 WHEN 'PARTIAL' THEN 10 WHEN 'NARROW' THEN 5 ELSE 0 END)
      + max(CASE WHEN upper(COALESCE(pipeline_runs.when_urgency, '')) = ANY (ARRAY['URGENT','LIVE','HIGH','ACT NOW']) THEN 10 ELSE 0 END)) AS base_points
   FROM pipeline_runs WHERE pipeline_runs.company IS NOT NULL
   GROUP BY pipeline_runs.company
 )
 SELECT COALESCE(ev.account, base.account) AS account,
   LEAST(round((COALESCE(base.base_points, 0)::numeric + COALESCE(ev.event_points, 0))::double precision)::integer, 100) AS score,
   COALESCE(ev.events, 0::bigint) AS engagement_events, ev.last_event,
   round((COALESCE(base.base_points, 0)::numeric + COALESCE(ev.hard_event_points, 0))::double precision)::integer AS hard_points,
   round(COALESCE(ev.soft_points, 0)::double precision)::integer AS soft_points
 FROM ev FULL JOIN base ON ev.account = base.account;

