-- Mirror an action's status back onto the cadence_steps row it came from,
-- so the existing approve/reject flow (which only ever updates `actions`)
-- keeps the cadence view in sync without any new approval-handler logic.
create or replace function sync_cadence_step_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $function$
begin
  if new.status is distinct from old.status then
    update cadence_steps set status = new.status where action_id = new.id;
  end if;
  return new;
end;
$function$;

drop trigger if exists trg_sync_cadence_step_status on actions;
create trigger trg_sync_cadence_step_status
  after update on actions
  for each row execute function sync_cadence_step_status();

-- ---------- Campaign template library (auto-matched cadences) ----------
-- "Select Campaign Template" (Brief Approval Handler) runs a priority-ordered
-- match against this table using the approved brief's when_urgency /
-- coverage_label / when_stage / trigger_type (NULL match_* column = wildcard
-- on that dimension; lowest `priority` wins). The matched row's `steps`
-- (action_type / delay_days / reason, in order) becomes the campaign's
-- cadence. `warm_reengage` (priority 99, every match_* column NULL) is the
-- catch-all fallback. Selection is fully automatic — no manual picker.
create table if not exists campaign_templates (
  id bigint primary key generated by default as identity,
  key text not null unique,
  name text not null,
  description text,
  match_urgency_in text[],       -- NULL = wildcard; else upper(when_urgency) must be in this array
  match_coverage_in text[],      -- NULL = wildcard; else upper(coverage_label) must be in this array
  match_stage_contains text,     -- NULL = wildcard; else upper(when_stage) ILIKE '%...%' this value
  priority integer not null,     -- lower wins; first match by this order is selected
  steps jsonb not null,          -- [{ action_type, delay_days, reason }, ...] in cadence order
  created_at timestamptz not null default now(),
  match_keywords text[],         -- NULL = wildcard; else trigger_type ILIKE '%keyword%' for any keyword
  goal text,                     -- plain-language objective of this template
  kpi_metric text,               -- the metric this template is judged against
  kpi_target text                -- target threshold/timeframe for kpi_metric
);

