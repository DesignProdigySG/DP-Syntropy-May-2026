CREATE VIEW public.dashboard_mmm_readiness AS
 WITH chan AS (
         SELECT o_1.funnel_stage,
            count(DISTINCT a.action_type) AS channels_used
           FROM campaign_objectives o_1
             JOIN actions a ON a.campaign_id = o_1.campaign_id AND (a.status = ANY (ARRAY['executed'::text, 'measured'::text]))
          GROUP BY o_1.funnel_stage
        )
 SELECT fs.key AS funnel_stage,
    fs.label,
    fs.sort_order,
    count(o.status) AS objectives_total,
    count(*) FILTER (WHERE o.status = 'met'::text) AS met,
    count(*) FILTER (WHERE o.status = 'missed'::text) AS missed,
    count(*) FILTER (WHERE o.status = 'open'::text) AS open,
    count(*) FILTER (WHERE o.status = ANY (ARRAY['met'::text, 'missed'::text])) AS labeled_rows,
    COALESCE(max(chan.channels_used), 0::bigint) AS channels_used,
    GREATEST(30::bigint, 10 * COALESCE(max(chan.channels_used), 0::bigint)) AS target_rows,
    LEAST(100::numeric, round(100.0 * count(*) FILTER (WHERE o.status = ANY (ARRAY['met'::text, 'missed'::text]))::numeric / GREATEST(30::bigint, 10 * COALESCE(max(chan.channels_used), 0::bigint))::numeric)) AS readiness_pct
   FROM funnel_stages fs
     LEFT JOIN campaign_objectives o ON o.funnel_stage = fs.key
     LEFT JOIN chan ON chan.funnel_stage = fs.key
  GROUP BY fs.key, fs.label, fs.sort_order;
REVOKE ALL ON public.dashboard_mmm_readiness FROM anon, authenticated, PUBLIC;
