CREATE VIEW public.dashboard_channel_performance AS
 WITH touches AS (
         SELECT engagement_events.source AS channel,
            count(*) AS touches
           FROM engagement_events
          WHERE engagement_events.event_type = ANY (ARRAY['email_open'::text, 'email_click'::text, 'ad_click'::text, 'page_visit'::text, 'reply'::text])
          GROUP BY engagement_events.source
        ), conv AS (
         SELECT attribution_last_touch.credited_source AS channel,
            count(*) AS conversions
           FROM attribution_last_touch
          WHERE attribution_last_touch.credited_source IS NOT NULL
          GROUP BY attribution_last_touch.credited_source
        )
 SELECT COALESCE(t.channel, c.channel) AS channel,
    COALESCE(t.touches, 0::bigint) AS touches,
    COALESCE(c.conversions, 0::bigint) AS conversions,
    round(100.0 * COALESCE(c.conversions, 0::bigint)::numeric / NULLIF(COALESCE(t.touches, 0::bigint), 0)::numeric, 0) AS conv_rate_pct
   FROM touches t
     FULL JOIN conv c ON t.channel = c.channel
  ORDER BY (COALESCE(c.conversions, 0::bigint)) DESC, (COALESCE(t.touches, 0::bigint)) DESC;
REVOKE ALL ON public.dashboard_channel_performance FROM anon, authenticated, PUBLIC;
GRANT SELECT ON public.dashboard_channel_performance TO anon;
GRANT SELECT ON public.dashboard_channel_performance TO authenticated;

