create table if not exists cadence_steps (
  id bigint primary key generated by default as identity,
  campaign_id bigint references campaigns(id),
  account text,
  step_number integer,
  delay_days integer default 0 not null,      -- days after campaign creation this step is due
  scheduled_for timestamptz,
  action_type text,
  target text,
  reason text,
  hypothesis text,
  predicted_metric text,
  predicted_direction text,
  threshold numeric,
  window_days integer,
  utm_campaign text,
  tracked_url text,
  outreach_draft text,
  status text default 'pending' not null,     -- pending | recommended | executed | measured | cancelled | skipped
  action_id bigint references actions(id),    -- set once Cadence Scheduler promotes this step to a real action
  created_at timestamptz default now(),
  -- Channel recommendation AI (2026-06-29, Phase 5) — "Channel Recommendation AI"
  -- (Brief Approval Handler) replaces the matched campaign_templates row's default
  -- steps with an LLM-recommended channel sequence built from account score, prior
  -- actions, channel performance, buying-group role/confirmation, and the template's
  -- own steps as a starting point. channel_source records which one actually won:
  -- 'ai' when the model returned a valid plan, 'template' on fallback (AI error, or
  -- output that fails JSON/vocabulary/range validation in "Parse AI Channel Plan").
  -- channel_reco_reason carries the AI's stated reason per step; null on fallback.
  channel_source text default 'template' not null,  -- 'ai' | 'template'
  channel_reco_reason text,
  -- Adaptive Decision Engine (2026-06-29, Phase 4) — set by the "Adaptive
  -- Decision Engine" workflow once the originating outcome is measured:
  -- 'escalated' (bumped to a higher-touch channel), 'paused' (scheduled_for
  -- pushed out due to zero engagement), 'stopped' (cancelled because the
  -- campaign goal was met elsewhere), 'reviewed' (no adaptive action
  -- needed), or null if not yet evaluated. The source query filters on
  -- adaptive_action is null, so this also makes the workflow idempotent —
  -- no separate "already processed" tracking table needed.
  adaptive_action text,
  adaptive_reason text
);

