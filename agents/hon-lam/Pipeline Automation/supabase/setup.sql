CREATE OR REPLACE FUNCTION public.set_action_client()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if new.client_id is null and new.campaign_id is not null then
    select client_id into new.client_id from campaigns where id = new.campaign_id;
  end if;
  return new;
end $function$;

CREATE OR REPLACE FUNCTION public.set_campaign_client()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if new.client_id is null and new.run_id is not null then
    select client_id into new.client_id from pipeline_runs where id = new.run_id;
  end if;
  return new;
end $function$;

CREATE OR REPLACE FUNCTION public.set_engagement_client()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if new.client_id is null and coalesce(new.campaign, '') <> '' then
    select a.client_id into new.client_id from actions a where a.utm_campaign = new.campaign limit 1;
  end if;
  return new;
end $function$;

CREATE OR REPLACE FUNCTION public.set_pipeline_run_client()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if new.client_id is null then
    new.client_id := nullif((select value from app_config where key='default_client_id'), '')::bigint;
  end if;
  return new;
end $function$;

CREATE OR REPLACE FUNCTION public.sync_cadence_step_status()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if new.status is distinct from old.status then
    update cadence_steps set status = new.status where action_id = new.id;
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.update_objective_status()
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
begin
  -- MET: an open objective whose campaign/account saw a success event in-window,
  -- attributed to the campaign (via action_id or utm match).
  update campaign_objectives obj
  set status = 'met', met_at = now()
  from campaigns cc
  where obj.campaign_id = cc.id
    and obj.status = 'open'
    and exists (
      select 1 from engagement_events ev
      where ev.account = cc.account
        and ev.event_type = any(obj.success_events)
        and ev.occurred_at >= obj.created_at
        and ev.occurred_at <  obj.created_at + make_interval(days => obj.window_days)
        and (
          ev.action_id in (select id from actions where campaign_id = obj.campaign_id)
          or ev.campaign in (select utm_campaign from actions where campaign_id = obj.campaign_id and utm_campaign is not null)
        )
    );

  -- MISSED: open objectives whose window has fully closed with no success.
  update campaign_objectives obj
  set status = 'missed'
  from campaigns cc
  where obj.campaign_id = cc.id
    and obj.status = 'open'
    and now() >= obj.created_at + make_interval(days => obj.window_days);
end;
$function$;

