CREATE VIEW public.account_score AS
 WITH event_weights AS (
         SELECT ee.account,
            ee.source,
            ee.event_type,
            ee.occurred_at,
                CASE ee.event_type
                    WHEN 'opportunity_created'::text THEN 50
                    WHEN 'meeting_booked'::text THEN 40
                    WHEN 'reply_or_meeting'::text THEN 30
                    WHEN 'reply'::text THEN 20
                    WHEN 'email_reply'::text THEN 20
                    WHEN 'form_fill'::text THEN 25
                    WHEN 'call_connected'::text THEN 25
                    WHEN 'registration'::text THEN 15
                    WHEN 'content_download'::text THEN 15
                    WHEN 'stage_change'::text THEN 15
                    WHEN 'partner_response'::text THEN 15
                    WHEN 'linkedin_accept'::text THEN 10
                    WHEN 'email_click'::text THEN 5
                    WHEN 'email_open'::text THEN 5
                    WHEN 'page_visit'::text THEN 5
                    WHEN 'profile_visit'::text THEN 5
                    ELSE 2
                END AS base_weight,
            row_number() OVER (PARTITION BY ee.account, ee.event_type ORDER BY ee.occurred_at) AS occurrence_rank
           FROM engagement_events ee
          WHERE ee.account IS NOT NULL
        ), ev AS (
         SELECT event_weights.account,
            sum(event_weights.base_weight::numeric *
                CASE event_weights.occurrence_rank
                    WHEN 1 THEN 1.0
                    WHEN 2 THEN 0.4
                    ELSE 0::numeric
                END) AS event_points,
            sum(event_weights.base_weight::numeric *
                CASE event_weights.occurrence_rank
                    WHEN 1 THEN 1.0
                    WHEN 2 THEN 0.4
                    ELSE 0::numeric
                END) FILTER (WHERE event_weights.source = ANY (ARRAY['ga4'::text, 'gmail'::text, 'salesforce'::text])) AS hard_event_points,
            sum(event_weights.base_weight::numeric *
                CASE event_weights.occurrence_rank
                    WHEN 1 THEN 1.0
                    WHEN 2 THEN 0.4
                    ELSE 0::numeric
                END) FILTER (WHERE event_weights.source = 'manual'::text) AS soft_points,
            count(*) AS events,
            max(event_weights.occurred_at) AS last_event
           FROM event_weights
          GROUP BY event_weights.account
        ), base AS (
         SELECT pipeline_runs.company AS account,
            max(
                CASE upper(COALESCE(pipeline_runs.coverage_label, ''::text))
                    WHEN 'BROAD'::text THEN 15
                    WHEN 'PARTIAL'::text THEN 10
                    WHEN 'NARROW'::text THEN 5
                    ELSE 0
                END) + max(
                CASE
                    WHEN upper(COALESCE(pipeline_runs.when_urgency, ''::text)) = ANY (ARRAY['URGENT'::text, 'LIVE'::text, 'HIGH'::text, 'ACT NOW'::text]) THEN 10
                    ELSE 0
                END) AS base_points
           FROM pipeline_runs
          WHERE pipeline_runs.company IS NOT NULL
          GROUP BY pipeline_runs.company
        )
 SELECT COALESCE(ev.account, base.account) AS account,
    LEAST(round((COALESCE(base.base_points, 0)::numeric + COALESCE(ev.event_points, 0::numeric))::double precision)::integer, 100) AS score,
    COALESCE(ev.events, 0::bigint) AS engagement_events,
    ev.last_event,
    round((COALESCE(base.base_points, 0)::numeric + COALESCE(ev.hard_event_points, 0::numeric))::double precision)::integer AS hard_points,
    round(COALESCE(ev.soft_points, 0::numeric)::double precision)::integer AS soft_points
   FROM ev
     FULL JOIN base ON ev.account = base.account;
REVOKE ALL ON public.account_score FROM anon, authenticated, PUBLIC;
GRANT SELECT ON public.account_score TO anon;
