CREATE VIEW public.attribution_last_touch AS
 WITH conversions AS (
         SELECT engagement_events.id,
            engagement_events.account,
            engagement_events.contact,
            engagement_events.source,
            engagement_events.event_type,
            engagement_events.campaign,
            engagement_events.action_id,
            engagement_events.value,
            engagement_events.occurred_at,
            engagement_events.metadata,
            engagement_events.ingested_at
           FROM engagement_events
          WHERE engagement_events.event_type = ANY (ARRAY['meeting_booked'::text, 'stage_change'::text, 'form_fill'::text])
        ), touches AS (
         SELECT engagement_events.id,
            engagement_events.account,
            engagement_events.contact,
            engagement_events.source,
            engagement_events.event_type,
            engagement_events.campaign,
            engagement_events.action_id,
            engagement_events.value,
            engagement_events.occurred_at,
            engagement_events.metadata,
            engagement_events.ingested_at
           FROM engagement_events
          WHERE engagement_events.event_type = ANY (ARRAY['email_click'::text, 'ad_click'::text, 'page_visit'::text, 'reply'::text])
        )
 SELECT c.id AS conversion_id,
    c.account,
    c.event_type AS conversion,
    c.occurred_at AS converted_at,
    t.campaign AS credited_campaign,
    t.source AS credited_source,
    t.occurred_at AS touch_at
   FROM conversions c
     LEFT JOIN LATERAL ( SELECT t_1.id,
            t_1.account,
            t_1.contact,
            t_1.source,
            t_1.event_type,
            t_1.campaign,
            t_1.action_id,
            t_1.value,
            t_1.occurred_at,
            t_1.metadata,
            t_1.ingested_at
           FROM touches t_1
          WHERE t_1.account = c.account AND t_1.occurred_at <= c.occurred_at
          ORDER BY t_1.occurred_at DESC
         LIMIT 1) t ON true;
